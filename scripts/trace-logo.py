#!/usr/bin/env python3
"""Traces the logo into clean vector shapes for the splash: the M, and the Ain (ع) with
its two fold shades. The splash draws these paths, so every edge stays sharp at any size.

The only source of the logo is a 297×320 raster (src/assets/logo-dark.webp). Each shape
is found on a 4× smooth upscale (so the traced edge lands between pixels, not on them),
then traced to Bézier curves with potrace:

  M        the M's outline, fitted as straight lines to the edges the Ain leaves visible
           (the artwork's M is a geometric letter; the part under the Ain is completed
           along those same lines)
  AIN      the ribbon's silhouette
  SHADE    the fold's darker band, and DEEP its darkest core — drawn soft inside the
           silhouette to keep the ribbon's twist

Output: src/components/site/logoPaths.ts (committed, so a clone needs no toolchain).

    pip install potracer numpy pillow scipy
    python3 scripts/trace-logo.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import potrace
from PIL import Image, ImageFilter
from scipy import ndimage

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "assets" / "logo-dark.webp"
OUT = ROOT / "src" / "components" / "site" / "logoPaths.ts"
SCALE = 4

# The M, as straight lines fitted to the edges the Ain leaves visible (a least-squares
# search over the outline's eight free parameters against the artwork at 4×). The left
# part's top sits lower than the right part's (y 96.3 against 85.3), as in the artwork.
M_OUTLINE = [
    (0, 96.3), (89.4, 96.3), (144.9, 246.7), (206.1, 85.3), (295.8, 85.3), (295.8, 320),
    (238, 320), (238, 158.6), (178.7, 320), (108.3, 320), (58, 157.6), (58, 320), (0, 320),
]


def field(img: Image.Image, fn) -> np.ndarray:
    a = np.asarray(img).astype(float)
    return fn(a[..., 0], a[..., 1], a[..., 2], a[..., 3])


def trace(mask: np.ndarray, turd: int = 40) -> str:
    """potrace → one SVG path, in the logo's own 297×320 units."""
    # potracer traces the "dark" pixels (below its black level), so the shape goes in as False.
    bm = potrace.Bitmap(~mask)
    plist = bm.trace(turdsize=turd, alphamax=1.0, opticurve=True, opttolerance=0.25)
    k = 1 / SCALE
    f = lambda p: f"{p.x * k:.2f} {p.y * k:.2f}"  # noqa: E731
    parts = []
    for curve in plist:
        parts.append(f"M{f(curve.start_point)}")
        for seg in curve.segments:
            if seg.is_corner:
                parts.append(f"L{f(seg.c)}L{f(seg.end_point)}")
            else:
                parts.append(f"C{f(seg.c1)} {f(seg.c2)} {f(seg.end_point)}")
        parts.append("Z")
    return "".join(parts)


def main() -> None:
    src = Image.open(SOURCE).convert("RGBA")
    big = src.resize((src.width * SCALE, src.height * SCALE), Image.LANCZOS)

    # The ribbon: how red-dominant each pixel is, weighted by its alpha, smoothed a touch.
    red = field(big, lambda r, g, b, a: np.clip((np.minimum(r - g, r - b) - 20) / 40, 0, 1) * a / 255)
    red = ndimage.gaussian_filter(red, 1.2)
    ain = red > 0.5
    ain = ndimage.binary_fill_holes(ain) & ~(ndimage.binary_fill_holes(ain) & ~ain & _big_holes(ain))
    # The fold's two shades: luminance bands inside the ribbon, smoothed into soft shapes.
    lum = field(big, lambda r, g, b, a: r)
    lum = ndimage.gaussian_filter(lum, 3)
    shade = (lum < 205) & ain
    deep = (lum < 158) & ain
    # Only the fold, top-left: the thin dark rim along the ribbon's lower edges is
    # anti-aliasing against the M, not shading.
    yy, xx = np.mgrid[0 : ain.shape[0], 0 : ain.shape[1]]
    fold = (yy < 140 * SCALE) & (xx < 90 * SCALE)
    shade &= fold
    deep &= fold
    shade = ndimage.binary_opening(shade, iterations=3)
    deep = ndimage.binary_opening(deep, iterations=3)

    ain_d = trace(ain)
    shade_d = trace(shade, 200)
    deep_d = trace(deep, 200)
    m_d = "M" + "L".join(f"{x:g} {y:g}" for x, y in M_OUTLINE) + "Z"

    # The ribbon's colours, measured: the main orange, the two fold shades.
    rgba = np.asarray(src).astype(int)
    r, g, b, a = (rgba[..., i] for i in range(4))
    rib = (r > g + 35) & (r > b + 35) & (a > 200)
    hexc = lambda arr: "#" + "".join(f"{int(v):02x}" for v in np.median(arr, axis=0))  # noqa: E731
    main_c = hexc(rgba[rib & (r >= 205)][:, :3])
    shade_c = hexc(rgba[rib & (r < 205) & (r >= 150)][:, :3])
    deep_c = hexc(rgba[rib & (r < 150)][:, :3])
    m_c = hexc(rgba[(abs(r - g) < 12) & (abs(g - b) < 12) & (r > 200) & (a > 250)][:, :3])

    OUT.write_text(
        "/* Generated by scripts/trace-logo.py from src/assets/logo-dark.webp — do not edit.\n"
        "   The logo as clean vector shapes, in its own 297×320 units. */\n\n"
        f"export const LOGO_W = 297;\nexport const LOGO_H = 320;\n\n"
        f"export const M_PATH = '{m_d}';\n"
        f"export const AIN_PATH = '{ain_d}';\n"
        f"export const AIN_SHADE_PATH = '{shade_d}';\n"
        f"export const AIN_DEEP_PATH = '{deep_d}';\n\n"
        "/** Colours measured from the artwork: the M on a dark ground, the ribbon, its shades. */\n"
        f"export const LOGO_COLORS = {{ m: '{m_c}', ain: '{main_c}', shade: '{shade_c}', deep: '{deep_c}' }} as const;\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: ain {len(ain_d)} chars, shade {len(shade_d)}, deep {len(deep_d)}")
    print("colours", main_c, shade_c, deep_c, m_c)


def _big_holes(mask: np.ndarray) -> np.ndarray:
    """The ribbon's real openings (the loop of the head): holes larger than a speck."""
    holes = ndimage.binary_fill_holes(mask) & ~mask
    lab, n = ndimage.label(holes)
    if n == 0:
        return holes
    sizes = ndimage.sum(holes, lab, range(1, n + 1))
    keep = np.zeros(n + 1, bool)
    keep[1:] = sizes > 400 * SCALE * SCALE / 16
    return keep[lab]


if __name__ == "__main__":
    main()
